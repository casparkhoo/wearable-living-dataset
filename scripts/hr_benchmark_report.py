"""Tables and figures for scripts/hr_benchmark.py (called by the score stage; can be re-run on results.json:
`python scripts/hr_benchmark_report.py`)."""
from __future__ import annotations

import json
import os

import numpy as np

import hr_benchmark as B

INK, INK2, GRID, SURF = '#0b0b0b', '#52514e', '#e4e3df', '#fcfcfb'
S1, S2, S3, S4 = '#2a78d6', '#eb6834', '#1baf7a', '#eda100'


def f1(x, d=1, sign=False):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return ''
    return f'{x:+.{d}f}' if sign else f'{x:.{d}f}'


def ring_row(name, r):
    name = name.replace('|', ' / ')
    a = r.get('all', {})
    if not a or not a.get('n'):
        return f'| {name} | 0 | | | | | | | | | | | |'
    rr, ac = r.get('rest_rec', {}), r.get('active_rec', {})
    ok = (a['mae'] < a['const_mae'] and ('mae_on_live_minutes' not in a or a['mae_on_live_minutes'] < LIVE_ON.get('mae', 1e9))
          and ac.get('n') and ac['mae'] < ac['const_mae'] and np.isfinite(ac.get('r', np.nan)) and ac['r'] > 0.5)
    return (f"| {name} | {a['n']} ({a['coverage'] * 100:.0f}%) | {f1(a['mae'])} | {f1(a['bias'], sign=True)} | "
            f"{f1(a['loa'][0], 0, True)} to {f1(a['loa'][1], 0, True)} | {a['within5']:.0f} / {a['within10']:.0f} | {f1(a['r'], 2)} | "
            f"{f1(a['const_mae'])} | {f1(rr.get('mae'))} ({f1(rr.get('const_mae'))}) | {f1(ac.get('mae'))} ({f1(ac.get('const_mae'))}) | "
            f"{f1(ac.get('r'), 2)} | {f1(a.get('mae_on_live_minutes'))} | {'yes' if ok else 'no'} |")


RING_HDR = ('| method | minutes (coverage) | MAE | bias | Bland-Altman 95% | within 5 / 10 bpm (%) | r | constant MAE (same minutes) | '
            'rest recordings MAE (constant) | activity recordings MAE (constant) | r on activity recordings | MAE on live-output minutes | better? |')
RING_SEP = '|' + '---|' * 13
LIVE_ON = {}


def write(out):
    lines = ['# HR benchmark tables (generated by scripts/hr_benchmark.py score; protocol in PROTOCOL.md)', '']
    # ---- checks
    lines += ['## Ring signal and pipeline checks', '',
              '| session | rows | segments (counter resets) | effective rate per segment (Hz) | index gaps (missing samples) | '
              'arrival-time 10 s windows with <240 or >260 samples | green / red / ir at 24-bit limits |', '|---|---|---|---|---|---|---|']
    for s, c in out['ring_checks'].items():
        lim = ' / '.join(f"{c[f'{ch}_at_24bit_limits'] * 100:.2f}%" for ch in B.CHANNELS)
        lines.append(f"| {s} | {c['rows']} | {c['segments']} | {', '.join(f'{x:.3f}' for x in c['seg_rate_hz'])} | "
                     f"{c['index_gaps']} ({c['missing_samples_in_gaps']}) | {c['arrival_window_counts']['share_outside_240_260'] * 100:.0f}% "
                     f"(5th-95th pct {c['arrival_window_counts']['p5']:.0f}-{c['arrival_window_counts']['p95']:.0f}) | {lim} |")
    lines += ['', 'Stored row order vs sample order (added after the first run): share of consecutive rows, in database '
              '`id` order, whose sample index goes backwards (resets excluded). Includes the training recordings of `hr_ring_stretch_v2`.', '',
              '| session | UTC date | consecutive pairs | out of order |', '|---|---|---|---|']
    for s, c in sorted(out.get('order_check', {}).items(), key=lambda t: int(t[0])):
        lines.append(f"| {s} | {c['utc_date']} | {c['pairs']} | {c['out_of_order']} ({100 * c['out_of_order'] / max(c['pairs'], 1):.1f}%) |")
    w = out['worker_check']
    lines += ['', f"Local ONNX vs running worker container on {w['windows']} ring windows: max abs difference {w['max_abs_diff']:.2g}, "
              f"mean cosine {w['mean_cosine']:.6f}.", '']
    # ---- synthetic
    lines += ['## Synthetic pulses (PaPaGei-S + probe, 5-fold CV, 1,500 windows, 40-180 bpm)', '',
              '| method | input | MAE | r |', '|---|---|---|---|']
    for k, d in out['synthetic'].items():
        lines.append(f"| {k.split('|')[0]} | {k.split('|')[1] if '|' in k else '25 Hz'} | {f1(d['mae'])} | {f1(d['r'], 3)} |")
    # ---- DaLiA
    lines += ['', '## PPG-DaLiA vs ECG (per 10 s window, held-out subjects, 5 folds of 3)', '',
              'rest = sitting, driving, working; active = stairs, table soccer, cycling, walking. Constant = mean training label.', '',
              '| method | condition | windows (coverage) | MAE all | bias | r | within 10 (%) | MAE rest | MAE active | constant MAE all / rest / active |',
              '|---|---|---|---|---|---|---|---|---|---|']
    for k, d in out['dalia'].items():
        a = d['all']
        name, cond = (k.split('|') + ['', ''])[:2]
        extra = ' (SQI-gated)' if k.endswith('|sqi') else ''
        lines.append(f"| {name}{extra} | {cond} | {a.get('n', 0)} ({a.get('coverage', 0) * 100:.0f}%) | {f1(a.get('mae'))} | "
                     f"{f1(a.get('bias'), sign=True)} | {f1(a.get('r'), 2)} | {f1(a.get('within10'), 0)} | {f1(d['rest'].get('mae'))} | "
                     f"{f1(d['active'].get('mae'))} | {f1(a.get('const_mae'))} / {f1(d['rest'].get('const_mae'))} / {f1(d['active'].get('const_mae'))} |")
    lines += ['', '### DaLiA signal quality (against ECG HR)', '', '| condition | group | windows | SNR at ECG HR (dB, median) | top peak within 10 bpm (%) | SQI median | rise fraction median |',
              '|---|---|---|---|---|---|---|']
    for k, d in out['dalia_signal'].items():
        c, g = k.split('|')
        lines.append(f"| {c} | {g} | {d['windows']} | {f1(d['snr_db_median'])} | {d['hit10_pct']:.0f} | {f1(d['sqi_median'], 2)} | {f1(d['rise_fraction_median'], 3)} |")
    # ---- ring signal
    lines += ['', '## Ring signal quality against the EmbracePlus (per 10 s window, minute reference)', '',
              '| channel | group | windows | SNR at reference (dB, median) | top peak within 10 bpm (%) | SQI median | rise fraction median | accel SD median |',
              '|---|---|---|---|---|---|---|---|']
    for k, d in out['ring_signal'].items():
        c, g = k.split('|')
        lines.append(f"| {c} | {g} | {d['windows']} | {f1(d['snr_db_median'])} | {d['hit10_pct']:.0f} | {f1(d['sqi_median'], 2)} | "
                     f"{f1(d['rise_fraction_median'], 3)} | {f1(d['acc_sd_median'])} |")
    lines += ['', '### Clean-window agreement (added after the first run; diagnostic)', '',
              'Windows with the ring still (accelerometer SD < 15), green SQI >= 0.6 and green/red/ir spectral peaks within 6 bpm; '
              'ring value = median of the three peaks, compared with the EmbracePlus minute.', '',
              '| group | clean / all windows | MAE | bias | within 10 (%) | ring range | EmbracePlus range |', '|---|---|---|---|---|---|---|']
    for g, d in out['clean_window_agreement'].items():
        if d.get('n'):
            lines.append(f"| {g} | {d['clean_windows']} / {d['all_windows']} | {f1(d['mae'])} | {f1(d['bias'], sign=True)} | {d['within10']:.0f} | "
                         f"{d['ring_range'][0]:.0f}-{d['ring_range'][1]:.0f} | {d['ref_range'][0]:.0f}-{d['ref_range'][1]:.0f} |")
        else:
            lines.append(f"| {g} | 0 / {d['all_windows']} | | | | | |")
    lines += ['', 'Best-SQI channel share: ' + ', '.join(f'{c} {v * 100:.0f}%' for c, v in out['best_channel_share'].items()),
              '', f"EmbracePlus adjacent-minute changes: median {out['reference_jumps']['median']:.0f}, 95th percentile "
              f"{out['reference_jumps']['p95']:.0f}, max {out['reference_jumps']['max']:.0f} bpm ({out['reference_jumps']['n']} pairs).", '']
    # ---- ring benchmark
    r = out['ring']
    LIVE_ON.clear()
    LIVE_ON.update(r['live_stored_v2']['all'])
    lines += ['## Ring vs EmbracePlus: every method, held out (per-minute median of >= 3 windows)', '',
              'Pooled over all ring days unless noted. Heads with source R or D+R are leave-one-UTC-day-out; source D never saw ring data; '
              'existing heads are scored on 66, 67, 140, 147, 148 only. Constant = mean EmbracePlus value of the other days. '
              '"MAE on live-output minutes" is on the minutes where the stored live head output exists (140, 147, 148), to compare with the live row. '
              f"Live stored output on those minutes: MAE {f1(LIVE_ON['mae'])}. "
              '"better?" applies the declared rule (beats constant pooled and on activity recordings with r > 0.5, and beats live on its minutes). '
              'Gate "sqi" keeps windows with spectral SQI at or above that channel\'s median.', '', RING_HDR, RING_SEP]
    for k in ('live_stored_v2', 'live_shown', 'constant_training_mean'):
        lines.append(ring_row(k, r[k]))
    for k in sorted(x for x in r if x.startswith('existing:')):
        lines.append(ring_row(k, r[k]))
    for k in sorted(x for x in r if '|' in x and not x.startswith(('existing:', 'papagei:'))):
        lines.append(ring_row(k, r[k]))
    for k in sorted(x for x in r if x.startswith('papagei:')):
        lines.append(ring_row(k, r[k]))
    sids = list(B.SESSIONS)
    lines += ['', '### Per recording: MAE (minutes) for baselines, existing heads, classical methods (no gate) and green/positive PaPaGei heads', '',
              '| method | ' + ' | '.join(str(s) for s in sids) + ' |', '|---|' + '---|' * len(sids)]
    keep = [k for k in r if k in ('live_stored_v2', 'live_shown', 'constant_training_mean') or k.startswith('existing:')
            or (k.endswith('|none') and not k.startswith('papagei:')) or (k.startswith('papagei:') and k.endswith(':pos|green|none'))]
    for k in keep:
        cells = []
        for s in sids:
            d = r[k].get(f's{s}', {})
            cells.append(f"{f1(d.get('mae'))} ({d.get('n', 0)})" if d.get('n') else '')
        lines.append(f"| {k.replace('|', ' / ')} | " + ' | '.join(cells) + ' |')
    with open(os.path.join(B.OUT, 'tables.md'), 'w', encoding='utf8') as f:
        f.write('\n'.join(lines) + '\n')
    figures(out)


def figures(out):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from matplotlib.colors import LinearSegmentedColormap
    os.makedirs(os.path.join(B.OUT, 'figures'), exist_ok=True)
    plt.rcParams.update({'font.size': 9, 'axes.edgecolor': INK2, 'axes.labelcolor': INK2, 'xtick.color': INK2,
                         'ytick.color': INK2, 'axes.facecolor': SURF, 'figure.facecolor': SURF})
    z = np.load(os.path.join(B.CACHE, 'ring_windows.npz'))
    f = z['spec_f']
    cmap = LinearSegmentedColormap.from_list('blue', [SURF, '#cde2fb', '#5598e7', '#184f95', '#0d366b'])
    minutes = {}
    for k in ('live_stored_v2',):
        for s, m, e, rr in out['ring'][k]['_minutes']:
            minutes.setdefault(s, []).append((m, e, rr))
    for sid in (140, 147, 148, 66):
        sel = np.where(z['session'] == sid)[0]
        sel = sel[np.argsort(z['centre'][sel])]
        t = (z['centre'][sel] - z['centre'][sel][0]) / 60000.0
        ref = {m: rr for s, m, e, rr in out['ring']['constant_training_mean']['_minutes'] if s == sid}
        live = {m: e for m, e, rr in minutes.get(sid, [])}
        fig, axes = plt.subplots(3, 1, figsize=(9, 7.5), sharex=True)
        for ax, ch in zip(axes, B.CHANNELS):
            P = z[f'spec_{ch}'][sel].T
            P = P / (P.max(0, keepdims=True) + 1e-12)
            ax.pcolormesh(t, f, P, cmap=cmap, shading='nearest', rasterized=True)
            ms = sorted(ref)
            tm = [(m * 60000 + 30000 - z['centre'][sel][0]) / 60000.0 for m in ms]
            ax.plot(tm, [ref[m] for m in ms], color=S2, lw=2, label='EmbracePlus (per minute)')
            lm = sorted(m for m in live if live[m] is not None)
            if lm:
                ax.plot([(m * 60000 + 30000 - z['centre'][sel][0]) / 60000.0 for m in lm], [live[m] for m in lm], 'o',
                        color=INK, ms=3, label='live PaPaGei head (per minute)')
            ax.set_ylim(35, 200)
            ax.set_ylabel(f'{ch}\nbpm')
            ax.grid(False)
        axes[0].legend(loc='upper right', frameon=False, fontsize=8)
        axes[0].set_title(f'Ring session {sid}: spectrum of each 10 s window (dark = strongest), per channel', loc='left', color=INK)
        axes[-1].set_xlabel('minutes from first window')
        fig.tight_layout()
        fig.savefig(os.path.join(B.OUT, 'figures', f'ring_spectrum_{sid}.png'), dpi=130)
        plt.close(fig)
    # DaLiA: classical and PaPaGei-ridge/knn MAE at 64 vs 25 Hz, rest vs active
    d = out['dalia']
    names = ['welch', 'welch_acc', 'acf', 'nk2', 'heartpy', 'track_viterbi', 'papagei:ridge', 'papagei:knn', 'papagei:hgb', 'papagei:mlp']
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.8), sharey=True)
    for ax, g in zip(axes, ('rest', 'active')):
        x = np.arange(len(names))
        for j, (cond, col) in enumerate((('D64', S1), ('D25', S2))):
            vals = [d.get(f'{n}|{cond}', {}).get(g, {}).get('mae', np.nan) for n in names]
            ax.bar(x + (j - 0.5) * 0.38, vals, 0.36, color=col, label={'D64': '64 Hz (native)', 'D25': '25 Hz (ring rate)'}[cond])
        c = d['constant_training_mean'][g]['mae']
        ax.axhline(c, color=INK2, lw=1, ls='--')
        ax.text(len(names) - 0.5, c, 'constant', color=INK2, ha='right', va='bottom', fontsize=8)
        ax.set_xticks(x, [n.replace('papagei:', 'PaPaGei ') for n in names], rotation=40, ha='right')
        ax.set_title(f'PPG-DaLiA {g} windows', loc='left', color=INK)
        ax.grid(axis='y', color=GRID, lw=0.6)
        ax.set_axisbelow(True)
        for sp in ('top', 'right'):
            ax.spines[sp].set_visible(False)
    axes[0].set_ylabel('MAE vs ECG (bpm)')
    axes[0].legend(frameon=False)
    fig.tight_layout()
    fig.savefig(os.path.join(B.OUT, 'figures', 'dalia_rate_cost.png'), dpi=130)
    plt.close(fig)


if __name__ == '__main__':
    with open(os.path.join(B.OUT, 'results.json')) as fh:
        write(json.load(fh))
